package com.xyz.ridebooking.observer;

/**
 * ============================================================================
 * DESIGN PATTERN: OBSERVER PATTERN (GoF - Behavioral)
 * PRESENTER: Presenter 1 (Observer Pattern Lead)
 *
 * PURPOSE & PROBLEM SOLVED:
 * In a real-time ride-booking system, multiple independent entities (such as
 * drivers, passengers, and database persistence loggers) need to react whenever
 * a ride's state changes (e.g., Requested -> Accepted -> Completed).
 *
 * Without the Observer Pattern, the booking engine would be tightly coupled
 * to every concrete subscriber class, requiring direct references and code
 * changes every time a new listener is added.
 *
 * HOW IT WORKS HERE:
 * - Subject / Observable: {@link RideCoordinator} maintains a list of subscribers.
 * - Observer Interface: {@link RideObserver} defines the standardized update() contract.
 * - Concrete Observers: {@link Driver}, {@link Rider}, and {@link DatabaseManager}.
 *
 * KEY TALKING POINTS FOR PRESENTER 1:
 * 1. Loose Coupling: The coordinator doesn't know concrete details of observers.
 * 2. Broadcast Communication: One state change triggers updates to all registered listeners.
 * 3. Dynamic Subscription: Observers can register or unregister at runtime.
 * ============================================================================
 */
public interface RideObserver {
    /**
     * Called by the Subject (RideCoordinator) when a ride status update occurs.
     *
     * @param rideId The unique identifier of the ride.
     * @param status The new status (e.g., "Requested", "Accepted", "Completed").
     */
    void update(String rideId, String status);

    /**
     * Retrieves the last status message generated by this observer.
     */
    String getLastNotification();
}
